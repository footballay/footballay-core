package com.footballay.core.infra.persistence.core.entity

import com.footballay.core.domain.league.MatchCollect
import jakarta.persistence.*
import org.hibernate.proxy.HibernateProxy

/**
 * uid 에 인덱스 필요 - 외부 노출 ID로 사용되기 때문
 */
@Entity
@Table(name = "league_core")
open class LeagueCore(
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    var id: Long? = null,
    /**
     * 외부 노출 ID
     */
    @Column(name = "uid", unique = true, nullable = false)
    var uid: String,
    @Column(nullable = false)
    var name: String,
    @Column(nullable = false)
    var available: Boolean = false,
    @Enumerated(EnumType.STRING)
    @Column(name = "match_collect", nullable = false)
    var matchCollect: MatchCollect = MatchCollect.NONE,
    /**
     * Provider data Sync 과정에서 자동으로 생성된 core 인 경우입니다. <br>
     * 관리자에 의해 체크가 필요한 경우를 나타냅니다. <br>
     */
    @Column(nullable = false)
    var autoGenerated: Boolean = true,
    @OneToMany(
        mappedBy = "league",
        cascade = [CascadeType.PERSIST, CascadeType.MERGE, CascadeType.REMOVE],
        orphanRemoval = true,
    )
    var leagueTeams: MutableSet<LeagueTeamCore> = mutableSetOf(),
) {
    final override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is LeagueCore) return false
        val thisId = if (this is HibernateProxy) hibernateLazyInitializer.internalIdentifier else id
        val otherId = if (other is HibernateProxy) other.hibernateLazyInitializer.internalIdentifier else other.id
        return thisId != null && thisId == otherId
    }

    final override fun hashCode(): Int = LeagueCore::class.java.hashCode()

    fun addTeam(team: TeamCore) {
        val existingRelation = leagueTeams.any { it.team?.id == team.id }
        if (!existingRelation) {
            val leagueTeam =
                LeagueTeamCore(
                    league = this,
                    team = team,
                )
            leagueTeams.add(leagueTeam)
        }
    }

    fun removeTeam(team: TeamCore) {
        val rel = leagueTeams.find { it.team.id == team.id } ?: return
        this.leagueTeams.remove(rel)
        team.leagueTeams.remove(rel)
    }

    override fun toString(): String =
        "LeagueCore(id=$id, uid='$uid', name='$name', available=$available, matchCollect=$matchCollect, autoGenerated=$autoGenerated)"
}
