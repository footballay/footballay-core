    fun findDistinctLeagueUidsWithAvailableFixturesReturnsEachLeagueOnce() {
        val previousSeason =
            leagueSeasonCoreRepository.save(
                LeagueSeasonCore(
                    league = testLeague,
                    seasonYear = 2024,
                    current = false,
                    autoGenerated = false,
                ),
            )
        val unavailableLeague =
            leagueCoreRepository.save(
                LeagueCore(
                    uid = "unavailable-fixture-league",
                    name = "Unavailable Fixture League",
                    available = true,
                    autoGenerated = false,
                ),
            )
        fixtureCoreRepository.saveAll(
            listOf(
                createFixture("available-current-1", Instant.parse("2025-08-01T10:00:00Z")),
                createFixture("available-current-2", Instant.parse("2025-08-01T11:00:00Z")),
                createFixture(
                    "available-previous-1",
                    Instant.parse("2024-08-01T10:00:00Z"),
                    leagueSeason = previousSeason,
                ),
                createFixture(
                    "unavailable-other-league",
                    Instant.parse("2025-08-02T10:00:00Z"),
