    }

    private fun createFixture(
        uid: String,
        kickoff: Instant,
        league: LeagueCore = testLeague,
        leagueSeason: LeagueSeasonCore? = seasonFor(league),
        available: Boolean = true,
    ): FixtureCore =
        FixtureCore(
            uid = uid,
            kickoff = kickoff,
            statusText = "Not Started",
            statusCode = FixtureStatusCode.NS,
            league = league,
            leagueSeason = leagueSeason,
            homeTeam = homeTeam,
            awayTeam = awayTeam,
            goalsHome = 0,
            goalsAway = 0,
            finished = false,
            available = available,
            autoGenerated = false,
        )

    private fun seasonFor(league: LeagueCore): LeagueSeasonCore =
        leagueSeasons.getOrPut(league.uid) {
            leagueSeasonCoreRepository.save(
                LeagueSeasonCore(
                    league = league,
                    seasonYear = 2025,
                    current = true,
                    autoGenerated = false,
                ),
            )
        }

    private fun createApiSportsBackedFixture(
        uid: String,
        kickoff: Instant,
        league: LeagueCore = testLeague,
        leagueSeason: LeagueSeasonCore? = seasonFor(league),
    ) {
        val fixture = fixtureCoreRepository.save(createFixture(uid, kickoff, league, leagueSeason))
        fixtureApiSportsRepository.save(
            FixtureApiSports(
                apiId = uid.hashCode().toLong(),
                core = fixture,
                round = "Round 1",
                season = null,
            ),
        )
    }
