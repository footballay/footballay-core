    @Test
    @DisplayName("available fixture 조회는 league season 경로로 모든 시즌의 경기만 반환한다")
    fun findAvailableFixturesByLeagueUidIncludesAllSeasons() {
        val previousSeason =
            leagueSeasonCoreRepository.save(
                LeagueSeasonCore(
                    league = testLeague,
                    seasonYear = 2024,
                    current = false,
                    autoGenerated = false,
                ),
            )
        val otherLeague =
            leagueCoreRepository.save(
                LeagueCore(
                    uid = "other-available-league",
                    name = "Other Available League",
                    available = true,
                    autoGenerated = false,
                ),
            )
        fixtureCoreRepository.saveAll(
            listOf(
                createFixture("available-current", Instant.parse("2025-08-01T10:00:00Z")),
                createFixture(
                    "available-previous",
                    Instant.parse("2024-08-01T10:00:00Z"),
                    leagueSeason = previousSeason,
                ),
                createFixture("unavailable-current", Instant.parse("2025-08-02T10:00:00Z"), available = false),
                createFixture("available-other", Instant.parse("2025-08-03T10:00:00Z"), league = otherLeague),
                createFixture(
                    "legacy-league-only",
                    Instant.parse("2025-08-04T10:00:00Z"),
                    leagueSeason = seasonFor(otherLeague),
                ),
            ),
        )
        em.flush()
        em.clear()

        val result = fixtureCoreRepository.findAvailableFixturesByLeagueUid(testLeague.uid)

        assertThat(result.map { it.uid }).containsExactlyInAnyOrder("available-current", "available-previous")
    }

