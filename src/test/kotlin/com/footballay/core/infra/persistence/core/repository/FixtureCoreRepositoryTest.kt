    @Test
    fun `fixture core 는 nullable league season 을 저장할 수 있다`() {
        val leagueSeason = leagueSeasons.getValue(testLeague.uid)
        fixtureCoreRepository.save(
            createFixture(
                uid = "fixture-with-league-season",
                kickoff = Instant.parse("2025-08-01T12:00:00Z"),
                leagueSeason = leagueSeason,
            ),
        )
        fixtureCoreRepository.save(
            createFixture(
                uid = "fixture-without-league-season",
                kickoff = Instant.parse("2025-08-01T13:00:00Z"),
                leagueSeason = null,
            ),
        )
        em.flush()
        em.clear()

        val found = fixtureCoreRepository.findByUid("fixture-with-league-season")

        assertThat(found.leagueSeason).isNotNull
        assertThat(found.leagueSeason?.id).isEqualTo(leagueSeason.id)
        assertThat(found.leagueSeason?.league?.id).isEqualTo(testLeague.id)
        assertThat(fixtureCoreRepository.findByUid("fixture-without-league-season").leagueSeason).isNull()
    }

    @Test
    @DisplayName("리그 날짜 조회 kickoff query는 timezone으로 계산된 시작 자정을 포함하고 종료 자정은 제외한다")
    fun findDistinctDefaultKickoffsByLeagueUidInRangeUsesInclusiveExclusiveInstants() {
        // Asia/Seoul 2025-03-02의 시작과 다음 날 시작을 UTC Instant로 변환한 범위입니다.
        val startInclusive = Instant.parse("2025-03-01T15:00:00Z")
        val endExclusive = Instant.parse("2025-03-02T15:00:00Z")
        createApiSportsBackedFixture("at-seoul-midnight", startInclusive)
        createApiSportsBackedFixture("same-seoul-midnight", startInclusive)
        createApiSportsBackedFixture("inside-range", endExclusive.minus(1, ChronoUnit.SECONDS))
        createApiSportsBackedFixture("at-next-seoul-midnight", endExclusive)
        em.flush()
        em.clear()

        val result =
            fixtureCoreRepository.findDistinctDefaultKickoffsByLeagueUidInRange(
                testLeague.uid,
                startInclusive,
                endExclusive,
            )

        assertThat(result).containsExactlyInAnyOrder(startInclusive, endExclusive.minus(1, ChronoUnit.SECONDS))
    }

