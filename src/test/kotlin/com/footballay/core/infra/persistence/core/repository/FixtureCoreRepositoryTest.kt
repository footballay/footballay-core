    @Test
    @DisplayName("리그 날짜 조회 kickoff query는 같은 리그의 과거와 현재 시즌 경기를 모두 반환한다")
    fun findDistinctDefaultKickoffsByLeagueUidInRangeIncludesAllLeagueSeasons() {
        val previousSeason =
            leagueSeasonCoreRepository.save(
                LeagueSeasonCore(
                    league = testLeague,
                    seasonYear = 2024,
                    current = false,
                    autoGenerated = false,
                ),
            )
        val currentSeason = leagueSeasons.getValue(testLeague.uid)
        val startInclusive = Instant.parse("2025-03-05T00:00:00Z")
        val endExclusive = Instant.parse("2025-03-06T00:00:00Z")
        val previousSeasonKickoff = Instant.parse("2025-03-05T10:00:00Z")
        val currentSeasonKickoff = Instant.parse("2025-03-05T12:00:00Z")
        createApiSportsBackedFixture("previous-season-fixture", previousSeasonKickoff, leagueSeason = previousSeason)
        createApiSportsBackedFixture("current-season-fixture", currentSeasonKickoff, leagueSeason = currentSeason)
        em.flush()
        em.clear()

        val result =
            fixtureCoreRepository.findDistinctDefaultKickoffsByLeagueUidInRange(
                testLeague.uid,
                startInclusive,
                endExclusive,
            )

        assertThat(result).containsExactlyInAnyOrder(previousSeasonKickoff, currentSeasonKickoff)
    }

